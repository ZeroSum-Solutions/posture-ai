// Regenerates content/index.ts from the files in content/muscles and
// content/exercises. Run after adding/removing content files:
//   node scripts/generate-content-index.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SKIP = new Set(['types.ts', 'registry.ts', 'index.ts'])

function collect(dir) {
  const entries = []
  for (const file of readdirSync(join(ROOT, 'content', dir)).sort()) {
    if (!file.endsWith('.ts') || SKIP.has(file)) continue
    const source = readFileSync(join(ROOT, 'content', dir, file), 'utf8')
    const match = source.match(/export const ([A-Za-z0-9_]+)\s*[:=]/)
    if (!match) {
      console.error(`SKIP ${dir}/${file}: no named export const found`)
      continue
    }
    entries.push({ name: match[1], path: `./${dir}/${file.replace(/\.ts$/, '')}` })
  }
  return entries
}

const muscles = collect('muscles')
const exercises = collect('exercises')

const banner = '// AUTO-GENERATED by scripts/generate-content-index.mjs — do not edit by hand.\n'
const imports = [
  ...muscles.map(e => `import { ${e.name} } from '${e.path}'`),
  ...exercises.map(e => `import { ${e.name} } from '${e.path}'`),
].join('\n')
const body = `
import type { MuscleContent, ExerciseContent } from './muscles/types'

export const ALL_MUSCLES: MuscleContent[] = [
${muscles.map(e => `  ${e.name},`).join('\n')}
]

export const ALL_EXERCISES: ExerciseContent[] = [
${exercises.map(e => `  ${e.name},`).join('\n')}
]
`
writeFileSync(join(ROOT, 'content/index.ts'), banner + imports + '\n' + body)
console.log(`content/index.ts: ${muscles.length} muscles, ${exercises.length} exercises`)
